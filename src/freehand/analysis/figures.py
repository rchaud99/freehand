"""`freehand figures`: the study figures of the objective / informed / stateless pilots and informed_models.

A port of the historical `informed_report.py` (learning-curve grid, first-try bars, summary table) and of
`objective_pilot.py --report`'s all-arms chart, on top of `analysis.report.build_rows`, so the figures in docs/figures/
are regenerated by this package from the imported runs:

  learning_curves_grid.png   rows = models (ordered by pooled first-try rate on the later squares), columns = rules;
                             first-try hit per post-change square (dots) and its 3-square running mean (line) for the
                             focus arm, the ideal code estimator dashed, the silent arm faint where it exists; squares
                             a capped or stopped episode never reached are hatched
  first_try_bars.png         later-square first-try rate per model, one panel per rule, the estimator as a line;
                             capped or stopped episodes are hatched with a hollow end marker (0/2 reached is not 0/15)
  learning_curves_all_arms.png   every arm of the models that ran all of them (Opus 5.5, GPT-6 Astra)
  informed_summary.csv       model x rule for the focus arm, the historical columns (`<arm>_summary.csv` for another
                             arm; `_legacy_scorer` appended under --scorer legacy)
Every title states the evidence level: episodes per cell and the seeds.

`scorer="corrected"` (default) uses freehand.scoring (an interrupted square whose first stroke missed counts as a
miss); `scorer="legacy"` reproduces the historical per-square-results scorer, to check parity with the old reports.
"""

from __future__ import annotations

import csv
import warnings
from collections import Counter
from pathlib import Path

import numpy as np

from freehand.analysis.charts import C_CODE, GRID, INK, KNOWN_ARM_COLOURS, MUTED, SURFACE, _plt
from freehand.analysis.report import build_rows
from freehand.scoring import legacy_squares_result_curve, squares_to_run

# Historical display names (informed_report.NAMES); unknown agents print as their folder name.
NAMES = {
    "claude-opus-5.5": "Opus 5.5",
    "gpt-6-astra": "GPT-6 Astra",
    "gpt-6-sol": "GPT-6 Sol",
    "claude-sonnet-5": "Sonnet 5 (crop px)",
    "gemini-3.8-flash": "Gemini 3.8 Flash (crop px)",
    "gpt-5.5": "GPT-5.5",
    "kimi-k3": "Kimi K3 (open)",
}
RULE_NAMES = {"rot13": "rotation 13°", "L3shear": "shear (L3 step 2)", "L6cam": "camera moved (L6)"}
ARM_LABELS = {
    "silent": "silent",
    "objective": "objective told",
    "informed_objective": "told a rule exists + objective",
    "stateless_image": "stateless: command log",
    "stateless_numeric": "stateless: log + landed ink",
    "code": "code estimator",
}
FOCUS_ARM = "informed_objective"
C_ARM, C_SILENT = KNOWN_ARM_COLOURS["informed_objective"], KNOWN_ARM_COLOURS["silent"]
TABLE_COLS = [
    "model",
    "condition",
    "later_first_try",
    "squares_to_3_in_a_row",
    "total_strokes",
    "squares_done",
    "tokens_in",
    "tokens_out",
    "tokens_reasoning",
    "cost",
    "status",
    "attribution",
]


# ---------------------------------------------------------------- rows
def study_rows(run_dirs: list[Path], scorer: str = "corrected") -> list[dict]:
    """Report rows (analysis.report) with `curve`, `later_first_try` and `squares_to_3_in_a_row` from the chosen
    scorer. Code references get arm "code" (their historical label)."""
    if scorer not in ("corrected", "legacy"):
        raise ValueError(f"scorer must be 'corrected' or 'legacy', not {scorer!r}")
    import json

    rows = build_rows(run_dirs)
    for r in rows:
        if r["kind"] == "reference":
            r["arm"] = "code"
        s = json.loads((Path(r["dir"]) / "summary.json").read_text())
        r["cost_exact"] = s["cost"]["usd_original"]  # unrounded (the table rounds once, to $0.001)
        if scorer == "legacy":
            c = legacy_squares_result_curve(s)
            r["curve"] = c
            later = [v for v in c[1:] if v is not None]
            r["later_first_try"] = f"{sum(later)}/{len(later)}"
            r["squares_to_3_in_a_row"] = squares_to_run(c)
        r["scorer"] = scorer
    return rows


def _later(r: dict) -> tuple[int, int]:
    h, n = (int(x) for x in r["later_first_try"].split("/"))
    return h, n


def find(rows: list[dict], agent: str, pert: str, arm: str) -> dict | None:
    return next((r for r in rows if r["agent"] == agent and r["perturbation"] == pert and r["arm"] == arm), None)


def model_order(rows: list[dict], arm: str = FOCUS_ARM) -> list[str]:
    """Models with the arm, by pooled later-square first-try rate (best first); ties keep first appearance."""
    tot: dict[str, list[int]] = {}
    for r in rows:
        if r["kind"] == "model" and r["arm"] == arm:
            h, n = _later(r)
            t = tot.setdefault(r["agent"], [0, 0])
            t[0] += h
            t[1] += n
    return sorted(tot, key=lambda a: -(tot[a][0] / tot[a][1]) if tot[a][1] else 1)


def rules_of(rows: list[dict]) -> list[str]:
    """The rules of the model rows: the historical order (rotation, shear, camera) first, then any others."""
    seen = list(dict.fromkeys(r["perturbation"] for r in rows if r["kind"] == "model"))
    return [p for p in RULE_NAMES if p in seen] + [p for p in seen if p not in RULE_NAMES]


def _mean3(curve: list) -> tuple[np.ndarray, np.ndarray]:
    y = np.array([np.nan if v is None else v for v in curve], float)
    m = np.array(
        [
            np.nanmean(y[max(0, k - 2) : k + 1]) if np.isfinite(y[max(0, k - 2) : k + 1]).any() else np.nan
            for k in range(len(y))
        ]
    )
    m[~np.isfinite(y)] = np.nan
    return y, m


def _xs(r: dict) -> np.ndarray:
    start = r["n_squares"] - len(r["curve"]) + 1
    return np.arange(start, r["n_squares"] + 1)


def _style(ax) -> None:
    ax.grid(axis="y", color=GRID, lw=0.8)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def _legend(fig, axes, ncol: int, y: float) -> None:
    h, lab = [], []
    for ax in axes.flat:
        for hh, ll in zip(*ax.get_legend_handles_labels(), strict=True):
            if ll not in lab:
                h.append(hh)
                lab.append(ll)
    fig.legend(
        h, lab, loc="upper center", ncol=min(ncol, len(h)) or 1, frameon=False, fontsize=9, bbox_to_anchor=(0.5, y)
    )


def _status_label(r: dict) -> str:
    cost = f"${r['cost_usd']:.2f}"
    return cost if r["status"] == "complete" else f"{cost} · {r['status']} at sq {r['squares_done']}"


def evidence(rows: list[dict]) -> str:
    """The evidence level of the model rows, for chart titles: "n = 1 episode per cell, seed 10"."""
    models = [r for r in rows if r["kind"] == "model"]
    per_cell = Counter((r["agent"], r["perturbation"], r["arm"]) for r in models)
    lo, n = min(per_cell.values(), default=0), max(per_cell.values(), default=0)
    seeds = sorted({r["seed"] for r in models})
    count = f"n = {n}" if lo == n else f"n = {lo}-{n}"
    return f"{count} episode{'s' if n != 1 else ''} per cell, " + (
        f"seed {seeds[0]}" if len(seeds) == 1 else f"seeds {', '.join(map(str, seeds))}"
    )


def _inconclusive(r: dict) -> bool:
    return r["status"] != "complete"


def _reached(r: dict) -> tuple[int, int]:
    """(later squares reached, later squares planned)."""
    later = r["curve"][1:]
    return sum(v is not None for v in later), len(later)


# ---------------------------------------------------------------- figures
def learning_curves_grid(rows: list[dict], out_png: Path, arm: str = FOCUS_ARM, title: str | None = None) -> None:
    plt = _plt()
    models, rules = model_order(rows, arm), rules_of(rows)
    fig, axes = plt.subplots(
        len(models),
        len(rules),
        figsize=(4.35 * len(rules), 2.15 * len(models) + 0.9),
        sharex=True,
        sharey=True,
        squeeze=False,
    )
    for i, agent in enumerate(models):
        for j, p in enumerate(rules):
            ax = axes[i, j]
            ref = find(rows, "adaptive", p, "code") or find(rows, "family_estimator", p, "code")
            if ref:
                ax.plot(_xs(ref), _mean3(ref["curve"])[1], color=C_CODE, lw=1.6, ls="--", label="code estimator")
            sil = find(rows, agent, p, "silent")
            if sil and arm != "silent":
                ax.plot(
                    _xs(sil), _mean3(sil["curve"])[1], color=C_SILENT, lw=1.6, alpha=0.35, label="silent (same model)"
                )
            r = find(rows, agent, p, arm)
            if r and _inconclusive(r):
                reached = [x for x, v in zip(_xs(r), r["curve"], strict=True) if v is not None]
                start = (reached[-1] if reached else _xs(r)[0] - 1) + 0.5
                if start < r["n_squares"] + 0.5:
                    ax.axvspan(
                        start,
                        r["n_squares"] + 0.5,
                        facecolor="none",
                        edgecolor=GRID,
                        hatch="///",
                        lw=0,
                        label="not reached (episode capped or stopped)",
                    )
            if r:
                y, m = _mean3(r["curve"])
                ax.plot(_xs(r), m, color=C_ARM, lw=2.2, label=ARM_LABELS.get(arm, arm))
                ax.scatter(_xs(r), y, s=14, color=C_ARM, alpha=0.7, zorder=3)
                h, n = _later(r)
                ax.text(
                    r["n_squares"] + 0.4,
                    1.3,
                    f"{h}/{n} · {_status_label(r)}",
                    ha="right",
                    va="center",
                    fontsize=8,
                    color=MUTED,
                )
            else:
                ax.text(0.5, 0.5, "not run", transform=ax.transAxes, ha="center", va="center", fontsize=9, color=MUTED)
            if i == 0:
                ax.set_title(RULE_NAMES.get(p, p), fontsize=10, color=INK)
            if j == 0:
                ax.set_ylabel(NAMES.get(agent, agent), fontsize=9.5, color=INK)
            if i == len(models) - 1:
                ax.set_xlabel("square (change after square 4)", fontsize=9)
            ax.set_ylim(-0.1, 1.45)
            ax.set_yticks([0, 1])
            _style(ax)
    fig.tight_layout(rect=(0, 0, 1, 1 - 0.95 / fig.get_figheight()))
    top = 1 - 0.1 / fig.get_figheight()
    scorer = rows[0].get("scorer", "corrected") if rows else "corrected"
    n_sq = max((r["n_squares"] for r in rows if r["kind"] == "model"), default=0)
    fig.suptitle(
        title
        or (
            "First-try hit on each square after the change, told a consistent rule exists + minimise "
            f"strokes ({evidence(rows)})\n{n_sq} squares in far-apart order; dots 0/1, line 3-square "
            f"mean; label: later-square hits/reached · cost; hatched: never reached; {scorer} scorer"
        ),
        fontsize=10.5,
        y=top,
        va="top",
    )
    _legend(fig, axes, 3, top - 0.5 / fig.get_figheight())
    fig.savefig(out_png, dpi=150, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)


def first_try_bars(rows: list[dict], out_png: Path, arm: str = FOCUS_ARM) -> None:
    plt = _plt()
    models, rules = model_order(rows, arm), rules_of(rows)
    fig, axes = plt.subplots(
        1, len(rules), figsize=(4.35 * len(rules), 0.5 * len(models) + 1.6), sharey=True, squeeze=False
    )
    yy = np.arange(len(models))[::-1]
    for ax, p in zip(axes[0], rules, strict=True):
        ref = find(rows, "adaptive", p, "code") or find(rows, "family_estimator", p, "code")
        for y, agent in zip(yy, models, strict=True):
            r = find(rows, agent, p, arm)
            if not r:
                ax.text(0.01, y, "not run", va="center", fontsize=8, color=MUTED)
                continue
            h, n = _later(r)
            v = h / n if n else 0.0
            if _inconclusive(r):
                reached, planned = _reached(r)
                ax.barh(y, v, height=0.62, facecolor=SURFACE, edgecolor=C_ARM, hatch="///", lw=1.0)
                ax.plot([v], [y], marker="o", ms=6, mfc=SURFACE, mec=C_ARM, mew=1.4, zorder=3)
                tag = f" · {r['status']}, {reached} of {planned} reached"
            else:
                ax.barh(y, v, height=0.62, color=C_ARM)
                ax.plot([v], [y], marker="o", ms=6, color=C_ARM, zorder=3)
                tag = ""
            ax.text(v + 0.03, y, f"{h}/{n} · ${r['cost_usd']:.2f}{tag}", va="center", fontsize=8, color=INK)
        if ref:
            h, n = _later(ref)
            ax.axvline(h / n, color=C_CODE, ls="--", lw=1.4)
            ax.text(h / n - 0.02, -0.75, f"code estimator {h}/{n}", ha="right", va="center", fontsize=8, color=MUTED)
        ax.set_title(RULE_NAMES.get(p, p), fontsize=10, color=INK)
        ax.set_ylim(-1.1, len(models) - 0.4)
        ax.set_xlim(0, 1.45)
        ax.set_xticks([0, 0.5, 1])
        ax.set_xlabel("first-try rate, squares 6–20", fontsize=9)
        ax.grid(axis="x", color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0][0].set_yticks(yy)
    axes[0][0].set_yticklabels([NAMES.get(m, m) for m in models], fontsize=9)
    scorer = rows[0].get("scorer", "corrected") if rows else "corrected"
    fig.suptitle(
        "Told a rule exists + minimise strokes: first-try rate on later squares "
        f"({evidence(rows)}; {scorer} scorer)\nlabel: hits/reached · cost per episode. Hatched, hollow "
        "marker: capped or stopped, inconclusive (0 of 2 reached is not 0 of 15)",
        fontsize=10.5,
    )
    fig.tight_layout()
    fig.savefig(out_png, dpi=150, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)


def all_arms_curves(
    rows: list[dict], out_png: Path, agents: tuple[str, ...] = ("claude-opus-5.5", "gpt-6-astra")
) -> None:
    """Every arm of the given models, faceted model x rule (the historical learning_curves_all_arms.png)."""
    plt = _plt()
    rules = rules_of(rows)
    arms = [a for a in ARM_LABELS if a != "code" and any(r["arm"] == a and r["agent"] in agents for r in rows)]
    colours = {**KNOWN_ARM_COLOURS, "code": C_CODE}
    style = {"code": "--", "stateless_image": ":", "stateless_numeric": ":"}
    jitter = dict(zip(arms, np.linspace(-0.05, 0.05, len(arms)) if len(arms) > 1 else [0.0], strict=True))
    fig, axes = plt.subplots(
        len(agents), len(rules), figsize=(4.35 * len(rules), 3.1 * len(agents)), sharex=True, sharey=True, squeeze=False
    )
    for i, m in enumerate(agents):
        for j, p in enumerate(rules):
            ax = axes[i, j]
            for arm, agent in [("code", "adaptive")] + [(a, m) for a in arms]:
                r = find(rows, agent, p, arm)
                if r is None:
                    continue
                y, mean = _mean3(r["curve"])
                ax.plot(_xs(r), mean, color=colours[arm], lw=2, ls=style.get(arm, "-"), label=ARM_LABELS[arm])
                ax.scatter(_xs(r), y + jitter.get(arm, 0.0), s=14, color=colours[arm], alpha=0.6, zorder=3)
            ax.set_title(f"{NAMES.get(m, m)} · {RULE_NAMES.get(p, p)}", fontsize=10, color=INK)
            ax.set_ylim(-0.1, 1.1)
            ax.set_yticks([0, 0.5, 1])
            _style(ax)
            if i == len(agents) - 1:
                ax.set_xlabel("square (change after square 4)")
            if j == 0:
                ax.set_ylabel("first-try hit\n(dots: 0/1; line: 3-square mean)")
    n_leg = len(arms) + 1
    scorer = rows[0].get("scorer", "corrected") if rows else "corrected"
    fig.suptitle(
        f"Do models carry a model of the change to the next square? ({evidence(rows)}; far-apart order; "
        f"{scorer} scorer)",
        y=1.05 + 0.03 * ((n_leg - 1) // 3),
        fontsize=11,
    )
    _legend(fig, axes, 3, 1.015)
    fig.tight_layout()
    fig.savefig(out_png, dpi=150, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)


def summary_table(rows: list[dict], out_csv: Path, arm: str = FOCUS_ARM) -> list[list]:
    """model x rule for one arm, the historical informed_models/summary.csv columns (cost rounded to $0.001)."""
    out = []
    for agent in model_order(rows, arm):
        for p in rules_of(rows):
            r = find(rows, agent, p, arm)
            if r:
                out.append(
                    [
                        NAMES.get(agent, agent),
                        p,
                        r["later_first_try"],
                        "" if r["squares_to_3_in_a_row"] is None else r["squares_to_3_in_a_row"],
                        r["total_strokes"],
                        r["squares_done"],
                        r["tokens_in"],
                        r["tokens_out"],
                        r["tokens_reasoning"],
                        round(r.get("cost_exact", r["cost_usd"]), 3),
                        r["status"],
                        r["attribution_keyword_screen"],
                    ]
                )
    with open(out_csv, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(TABLE_COLS)
        w.writerows(out)
    return out


def table_name(arm: str = FOCUS_ARM, scorer: str = "corrected") -> str:
    """informed_summary.csv (the tracked docs/figures name) for the informed arm; <arm>_summary.csv otherwise."""
    stem = "informed" if arm == FOCUS_ARM else arm
    return f"{stem}_summary{'_legacy_scorer' if scorer == 'legacy' else ''}.csv"


def write_figures(run_dirs: list[Path], out: Path, scorer: str = "corrected", arm: str = FOCUS_ARM) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    rows = study_rows(run_dirs, scorer)
    focus = [r for r in rows if r["arm"] in (arm, "silent", "code")]
    written: dict[str, str] = {}
    notes: list[str] = []
    if any(r["arm"] == arm for r in rows):
        learning_curves_grid(focus, out / "learning_curves_grid.png", arm)
        first_try_bars(focus, out / "first_try_bars.png", arm)
        summary_table(rows, out / table_name(arm, scorer), arm)
        written.update(grid="learning_curves_grid.png", bars="first_try_bars.png", table=table_name(arm, scorer))
    else:
        arms = sorted({r["arm"] for r in rows if r["kind"] == "model"})
        notes.append(
            f"no episode of the arm {arm!r} in these runs (arms: {arms}): no grid, bars or table written; pass --arm"
        )
        warnings.warn(notes[-1], stacklevel=2)
    agents = tuple(
        a for a in ("claude-opus-5.5", "gpt-6-astra") if len({r["arm"] for r in rows if r["agent"] == a}) > 1
    )
    if agents:
        all_arms_curves(rows, out / "learning_curves_all_arms.png", agents)
        written["all_arms"] = "learning_curves_all_arms.png"
    return {"out": str(out), "scorer": scorer, "models": model_order(rows, arm), "files": written, "warnings": notes}
